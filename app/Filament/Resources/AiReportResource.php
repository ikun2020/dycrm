<?php

namespace App\Filament\Resources;

use App\Filament\Resources\AiReportResource\Pages;
use App\Filament\Resources\Concerns\ChecksMenuPermission;
use App\Models\AiReport;
use Filament\Actions\BulkActionGroup;
use Filament\Actions\DeleteBulkAction;
use Filament\Actions\EditAction;
use Filament\Forms;
use Filament\Resources\Resource;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Tables;
use Filament\Tables\Table;

class AiReportResource extends Resource
{
    use ChecksMenuPermission;

    protected static ?string $model = AiReport::class;

    protected static ?string $menuPermissionKey = 'ai-reports';

    protected static string|\BackedEnum|null $navigationIcon = 'heroicon-o-sparkles';

    protected static string|\UnitEnum|null $navigationGroup = 'AI分析';

    protected static ?string $modelLabel = 'AI报告';

    protected static ?string $pluralModelLabel = 'AI报告';

    public static function form(Schema $schema): Schema
    {
        return $schema->components([
            Section::make(__('Report'))
                ->description('查看或修正 AI 诊断结果，建议保留摘要、风险点和下一步动作，便于后续跟进。')
                ->icon('heroicon-o-sparkles')
                ->columnSpanFull()
                ->columns(['md' => 2, 'xl' => 3])
                ->components([
                    Forms\Components\Select::make('creator_id')->label(__('Creator'))->relationship('creator', 'nickname')->searchable()->preload()->required(),
                    Forms\Components\TextInput::make('status')->label(__('Status'))->disabled()->dehydrated(false),
                    Forms\Components\TextInput::make('score')->label(__('Score'))->numeric()->minValue(1)->maxValue(10),
                    Forms\Components\TextInput::make('grade')->label(__('Grade'))->maxLength(10),
                    Forms\Components\Select::make('generated_by')->label(__('Generated By'))->relationship('generatedBy', 'name')->searchable()->preload(),
                    Forms\Components\DateTimePicker::make('generated_at')->label(__('Generated At'))->seconds(false),
                    Forms\Components\Textarea::make('summary')->label(__('Summary'))->rows(5)->required()->columnSpanFull(),
                    Forms\Components\Textarea::make('risk_points')->label(__('Risk Points'))->rows(4)->columnSpanFull(),
                    Forms\Components\Textarea::make('next_steps')->label(__('Next Steps'))->rows(4)->columnSpanFull(),
                    Forms\Components\Textarea::make('error_message')->label(__('Error Message'))->rows(3)->disabled()->dehydrated(false)->columnSpanFull(),
                ]),
            Section::make(__('Detailed Analysis'))
                ->icon('heroicon-o-document-text')
                ->columnSpanFull()
                ->collapsible()
                ->components([
                    Forms\Components\Textarea::make('raw_payload.content')
                        ->label(__('Detailed Analysis'))
                        ->rows(14)
                        ->disabled()
                        ->dehydrated(false)
                        ->columnSpanFull(),
                ]),
        ]);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->defaultSort('generated_at', 'desc')
            ->columns([
                Tables\Columns\TextColumn::make('creator.nickname')->label(__('Creator'))->searchable()->sortable(),
                Tables\Columns\TextColumn::make('status')
                    ->label(__('Status'))
                    ->formatStateUsing(fn (string $state): string => self::statusOptions()[$state] ?? $state)
                    ->badge()
                    ->color(fn (string $state): string => match ($state) {
                        'pending' => 'gray',
                        'processing' => 'warning',
                        'failed' => 'danger',
                        default => 'success',
                    }),
                Tables\Columns\TextColumn::make('score')->label(__('Score'))->sortable()->badge(),
                Tables\Columns\TextColumn::make('grade')->label(__('Grade'))->sortable(),
                Tables\Columns\TextColumn::make('summary')
                    ->label(__('Summary'))
                    ->limit(80)
                    ->wrap()
                    ->visibleFrom('md')
                    ->extraAttributes(['class' => 'dycrm-ai-report-summary-cell']),
                Tables\Columns\TextColumn::make('generatedBy.name')->label(__('Generated By'))->visibleFrom('md'),
                Tables\Columns\TextColumn::make('generated_at')->label(__('Generated At'))->dateTime('Y-m-d H:i')->sortable(),
            ])
            ->actions([
                EditAction::make()
                    ->visible(fn (AiReport $record): bool => self::canEdit($record)),
            ])
            ->bulkActions([
                BulkActionGroup::make([
                    DeleteBulkAction::make()
                        ->visible(fn (): bool => self::canDeleteAny()),
                ]),
            ]);
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListAiReports::route('/'),
            'edit' => Pages\EditAiReport::route('/{record}/edit'),
        ];
    }

    public static function statusOptions(): array
    {
        return [
            'pending' => __('Pending'),
            'processing' => __('Processing'),
            'completed' => __('Completed'),
            'failed' => __('Failed'),
        ];
    }
}
